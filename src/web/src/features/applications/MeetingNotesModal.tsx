'use client';

import { useEffect, useState } from 'react';
import { useMutation } from '@tanstack/react-query';
import { api } from '@/api';
import { Button, Input, Modal, Textarea, toast } from '@/components/ui';
import type { Interview, ModalProps } from './application-types';

export function MeetingNotesModal({
  interview,
  opened,
  onClose,
  onSaved,
}: ModalProps & { interview: Interview }) {
  const [notes, setNotes] = useState(interview.meetingNotes ?? '');
  const [source, setSource] = useState(interview.meetingNotesSource ?? '');
  useEffect(() => {
    if (!opened) return;
    setNotes(interview.meetingNotes ?? '');
    setSource(interview.meetingNotesSource ?? '');
  }, [interview.meetingNotes, interview.meetingNotesSource, opened]);
  const mutation = useMutation({
    mutationFn: () =>
      api.put(`/api/interviews/${interview.id}/meeting-notes`, {
        notes,
        source: source.trim() || null,
      }),
    onSuccess: () => {
      onSaved();
      onClose();
      toast.success('Meeting notes saved');
    },
    onError: (error: Error) => toast.error('Could not save the notes', error.message),
  });
  return (
    <Modal
      opened={opened}
      onClose={onClose}
      title="Meeting notes"
      size="xl"
      footer={
        <>
          <Button variant="secondary" onClick={onClose}>
            Cancel
          </Button>
          <Button
            disabled={!notes.trim()}
            loading={mutation.isPending}
            onClick={() => mutation.mutate()}
          >
            Save notes
          </Button>
        </>
      }
    >
      <div className="space-y-4">
        <Input
          label="Generated by"
          description="For example: Fireflies, Fathom, Otter, or manual import"
          value={source}
          maxLength={120}
          onChange={(event) => setSource(event.currentTarget.value)}
        />
        <Textarea
          label="Notes"
          description="Paste the meeting assistant's notes or transcript here."
          minRows={14}
          maxRows={24}
          maxLength={100_000}
          value={notes}
          onChange={(event) => setNotes(event.currentTarget.value)}
        />
      </div>
    </Modal>
  );
}
